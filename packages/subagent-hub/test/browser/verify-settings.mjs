// Isolated real-component checks. Saves touch fixture memory only, never a profile or model.
async page => {
  const base = page.url().split('?')[0]
  const checks = [], errors = []
  const check = (condition, name) => { if (!condition) throw new Error(name); checks.push(name) }
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1366, height: 900 })
  await page.goto(base)
  await page.getByRole('tab', { name: '角色', exact: true }).waitFor()
  const save = () => page.locator('.sah-footer').getByRole('button', { name: '保存', exact: true })
  const bounds = () => page.evaluate(() => {
    const root = document.querySelector('.sah-workspace'), content = document.querySelector('.sah-workspace-content'), footer = document.querySelector('.sah-footer')
    const r = root.getBoundingClientRect(), c = content.getBoundingClientRect(), f = footer.getBoundingClientRect()
    return { height: r.height, bottom: r.bottom, footerBottom: f.bottom, footerTop: f.top, contentBottom: c.bottom,
      viewport: innerHeight, overflow: root.scrollWidth > root.clientWidth, position: getComputedStyle(footer).position }
  })
  const first = await bounds()
  check(first.bottom <= first.viewport && first.contentBottom <= first.footerTop + 1 && first.position === 'static', 'footer reserves space inside the desktop viewport')
  check(!first.overflow, 'desktop settings have no horizontal overflow')
  await page.locator('.sah-workspace').screenshot({ path: 'output/settings-a/roles-dark.png' })
  await page.getByRole('tab', { name: '模型', exact: true }).click()
  check(await page.locator('.sah-route-editor').count() === 0, 'models begin as compact collapsed summaries')
  check(Math.abs((await bounds()).height - first.height) < 1, 'switching to models retains the frame height')
  await page.getByRole('searchbox', { name: '搜索模型、供应商或标签' }).fill('vision')
  check(await page.locator('.sah-route-card').count() === 1, 'model search includes capability tags')
  check(await page.locator('.sah-route-card').getByRole('button', { name: '上移', exact: true }).isDisabled(), 'filtered views cannot accidentally reorder hidden entries')
  await page.getByRole('searchbox', { name: '搜索模型、供应商或标签' }).fill('')
  await page.getByRole('combobox', { name: '模型展示方式' }).selectOption('provider')
  check(await page.locator('.sah-provider-group').count() === 2, 'provider grouping uses the configured routes')
  check(await page.evaluate(() => qa.saves.length) === 0, 'search and grouping perform no configuration writes')
  await page.getByRole('combobox', { name: '模型展示方式' }).selectOption('order')
  await page.locator('.sah-route-card').nth(1).locator('.sah-route-toggle').click()
  await page.locator('.sah-route-editor').getByRole('textbox', { name: '路由名', exact: true }).fill('minimax-fast')
  await save().click()
  await page.waitForFunction(() => qa.value().routes.some(route => route.id === 'minimax-fast'))
  check(await page.evaluate(() => qa.value().agents.find(agent => agent.id === 'reviewer').routes.includes('minimax-fast')), 'editing route identity preserves role references on save')
  check(await page.locator('.sah-route-editor').count() === 1, 'saving preserves expansion across rebuilt row identities')
  await page.evaluate(() => { qa.saveDelay = 400 })
  await page.locator('.sah-route-editor').getByRole('textbox', { name: '备注', exact: true }).fill('延迟保存检查')
  await save().click()
  await page.locator('.sah-route-card').nth(1).locator('.sah-route-toggle').click()
  await page.waitForFunction(() => qa.value().routes.some(route => route.note === '延迟保存检查'))
  check(await page.locator('.sah-route-editor').count() === 0, 'a slow save preserves the latest collapse action')
  await page.evaluate(() => { qa.saveDelay = 0 })
  await page.locator('.sah-route-card').nth(1).locator('.sah-route-toggle').click()
  await page.locator('.sah-route-card').nth(1).getByRole('button', { name: '上移', exact: true }).click()
  await save().click()
  await page.waitForFunction(() => qa.value().routes[0].id === 'minimax-fast')
  check(await page.evaluate(() => qa.value().routes.map(route => route.id).join(',') === 'minimax-fast,flash'), 'model reordering saves only the explicit new configuration order')
  await page.getByRole('tab', { name: '角色', exact: true }).click()
  await page.getByRole('button', { name: '全部折叠', exact: true }).click()
  await page.locator('.sah-role-accordion').first().locator('.sah-drag-handle').focus()
  await page.keyboard.press('ArrowDown')
  await page.waitForFunction(() => document.querySelectorAll('.sah-role-toggle strong')[1]?.textContent === '功能开发' && document.activeElement?.classList.contains('sah-drag-handle'))
  await page.keyboard.press('ArrowDown')
  await page.waitForFunction(() => document.querySelectorAll('.sah-role-toggle strong')[2]?.textContent === '功能开发')
  check(await page.evaluate(() => document.activeElement?.classList.contains('sah-drag-handle')), 'keyboard sorting supports repeated moves without losing handle focus')
  await page.locator('.sah-footer').getByRole('button', { name: '放弃修改', exact: true }).click()
  await page.locator('.sah-role-accordion').first().locator('.sah-drag-handle').dragTo(page.locator('.sah-role-accordion').last())
  await save().click()
  await page.waitForFunction(() => qa.value().agents[2].id === 'builder')
  check(await page.evaluate(() => qa.value().agents.map(agent => agent.id).join(',') === 'reviewer,researcher,builder'), 'role drag sorting preserves the selected role and persists its order')
  await page.getByRole('tab', { name: '模型', exact: true }).click()
  await page.locator('.sah-route-card').first().getByRole('button', { name: '删除路由', exact: true }).click()
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  check(await page.locator('.sah-route-card').count() === 2 && await page.locator('.sah-route-editor').count() === 1, 'delete undo restores the route and opens its editor')
  await page.getByRole('button', { name: '添加路由', exact: true }).click()
  const added = page.locator('.sah-route-card').last()
  await added.getByRole('textbox', { name: '路由名', exact: true }).fill('flash')
  await added.locator('.sah-route-toggle').click()
  await page.getByRole('searchbox', { name: '搜索模型、供应商或标签' }).fill('vision')
  const writes = await page.evaluate(() => qa.saves.length)
  await save().click()
  await page.waitForFunction(() => document.activeElement?.getAttribute('aria-invalid') === 'true')
  check(await page.getByRole('searchbox', { name: '搜索模型、供应商或标签' }).inputValue() === '', 'save reveals invalid entries hidden by filters')
  check(await page.evaluate(() => qa.saves.length) === writes, 'invalid collapsed rows prevent a configuration write')
  await page.locator('.sah-footer').getByRole('button', { name: '放弃修改', exact: true }).click()
  check(await page.locator('.sah-route-card').count() === 2 && await save().isDisabled(), 'discard restores the latest saved configuration')
  if (await page.getByRole('button', { name: '全部折叠', exact: true }).count()) await page.getByRole('button', { name: '全部折叠', exact: true }).click()
  await page.getByRole('button', { name: '全部展开', exact: true }).click()
  await page.locator('.sah-workspace').screenshot({ path: 'output/settings-a/models-dark.png' })
  await page.getByRole('tab', { name: '常规', exact: true }).click()
  check(Math.abs((await bounds()).height - first.height) < 1, 'general settings share the same stable frame')
  await page.getByRole('spinbutton', { name: '每个会话的并发上限' }).fill('8')
  await page.getByRole('tab', { name: '模型', exact: true }).click()
  await page.getByRole('tab', { name: '常规', exact: true }).click()
  check(await page.getByRole('spinbutton', { name: '每个会话的并发上限' }).inputValue() === '8', 'switching tabs retains unsaved general edits')
  await page.locator('.sah-workspace').screenshot({ path: 'output/settings-a/general-dark.png' })
  await page.locator('.sah-footer').getByRole('button', { name: '放弃修改', exact: true }).click()
  await page.evaluate(() => qa.externalUpdate({ routes: [...qa.value().routes, ...Array.from({ length: 18 }, (_, i) => ({ id: 'extra-' + i, provider: 'deepseek-official', model: 'synthetic-' + i, tags: ['fast'], note: '滚动验收 ' + i }))] }))
  await page.getByRole('tab', { name: '模型', exact: true }).click()
  await page.locator('.sah-workspace-content').evaluate(el => { el.scrollTop = el.scrollHeight })
  const long = await bounds()
  check(long.contentBottom <= long.footerTop + 1 && long.footerBottom <= long.viewport, 'long lists scroll independently while the footer remains unobstructed')
  check(await page.locator('.sah-route-card').last().evaluate(el => el.getBoundingClientRect().bottom <= document.querySelector('.sah-footer').getBoundingClientRect().top), 'the last model row can scroll completely above the action bar')
  await page.goto(base + '?loading=1')
  await page.getByText('正在读取配置…', { exact: true }).waitFor()
  await page.evaluate(() => qa.finishLoading())
  await page.waitForFunction(() => document.querySelector('.sah-role-accordion[data-open=true]'))
  check(await page.locator('.sah-role-accordion[data-open=true]').count() === 1, 'asynchronously loaded roles select the first entry consistently')
  await page.goto(base + '?theme=light&lang=en')
  await page.getByRole('tab', { name: 'Models', exact: true }).click()
  await page.getByRole('button', { name: 'Expand all', exact: true }).click()
  check(!(await bounds()).overflow, 'English light desktop layout retains usable width')
  await page.getByRole('button', { name: 'Collapse all', exact: true }).focus()
  await page.keyboard.press('Shift+Tab')
  await page.keyboard.press('Tab')
  check(await page.evaluate(() => getComputedStyle(document.activeElement).outlineStyle !== 'none'), 'keyboard actions have a visible focus indicator')
  await page.locator('.sah-workspace').screenshot({ path: 'output/settings-a/models-light-en.png' })
  check(errors.length === 0, 'no unhandled component errors')
  return { passed: checks.length, checks, errors }
}
